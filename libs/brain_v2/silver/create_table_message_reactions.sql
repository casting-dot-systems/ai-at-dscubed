DROP TABLE IF EXISTS SILVER.MESSAGE_REACTIONS CASCADE;

CREATE TABLE IF NOT EXISTS SILVER.MESSAGE_REACTIONS (
    REACTION_ID UUID PRIMARY KEY DEFAULT GEN_RANDOM_UUID (),
    ORG_ID TEXT NOT NULL,
    SYSTEM TEXT NOT NULL DEFAULT 'discord',
    MESSAGE_ID TEXT NOT NULL,
    REACTION TEXT NOT NULL,
    MEMBER_ID UUID REFERENCES CATALOG.MEMBERS (MEMBER_ID) ON DELETE SET NULL,
    CREATED_AT_TS TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UPDATED_AT_TS TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Ensure ON CONFLICT works:
CREATE UNIQUE INDEX UX_MESSAGE_REACTIONS ON SILVER.MESSAGE_REACTIONS (MESSAGE_ID, REACTION, MEMBER_ID);

-- Speed up lookups
CREATE INDEX IDX_REACTIONS_MESSAGE ON SILVER.MESSAGE_REACTIONS (MESSAGE_ID);

CREATE INDEX IDX_REACTIONS_MEMBER ON SILVER.MESSAGE_REACTIONS (MEMBER_ID);
